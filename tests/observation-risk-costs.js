"use strict";
const assert = require("node:assert/strict"), fs = require("node:fs"), vm = require("node:vm"), path = require("node:path");
const { loadFX, root } = require("./helpers"), { FX, context } = loadFX();
const near = (actual, expected) => assert.ok(Math.abs(actual - expected) < 1e-9, `${actual} != ${expected}`);
const time = (value) => Date.parse(value) / 1000;
assert.equal(FX.costs.fingerprint(), "model-v1");
assert.equal(FX.costs.swapDays(time("2026-01-14T21:30:00Z"), time("2026-01-14T22:15:00Z")), 3, "winter rollover");
assert.equal(FX.costs.swapDays(time("2026-07-15T20:30:00Z"), time("2026-07-15T21:15:00Z")), 3, "summer rollover");
assert.equal(FX.costs.swapDays(time("2026-07-15T21:00:00Z"), time("2026-07-15T21:15:00Z")), 0, "opening at the rollover is not charged retroactively");
const profile = { pairs: { EURUSD: { spread: 1, commission: .4, slippage: .2, swap_long: 2 } } };
const trade = { fill_price: 1.1, stop0: 1.09, dir: 1, fill_time: time("2026-07-14T20:00:00Z"), parts: [{ w: .5, closed_at: time("2026-07-14T20:30:00Z") }, { w: .5, closed_at: time("2026-07-16T22:00:00Z") }] };
const cost = FX.costs.calculate(trade, FX.costs.info("EURUSD", profile), time("2026-07-16T22:00:00Z"));
near(cost.total, .066); near(cost.swap, .05);
assert.throws(() => FX.costs.normalize({ pairs: { EURUSD: { commission: -1 } } }));
const signal = { id: "example-H1-EURUSD-90", strategy: "example-H1", strategy_name: "Пример", version: 1, cost_model: "model-v1", pair: "EURUSD", tf: "H1", style: "day", status: "pending", signal_time: 90, valid_until: 500, orders: [{ dir: 1, type: "stop", entry: 1.1, stop: 1.09 }] };
const store = new context.FXObserved.Store(); store.ingest([signal], 100, () => true);
signal.orders[0].entry = 9;
assert.equal(store.list()[0].initial.orders[0].entry, 1.1, "initial record is a copy of what was shown");
signal.orders[0].entry = 1.1;
const closed = { ...signal, status: "closed", fill_time: 200, exit_time: 300, r: 1 };
store.ingest([closed], 310, () => true);
assert.equal(store.summary().closed, 1); assert.equal(store.summary().average, 1);
assert.equal(store.list()[0].initial.status, "pending", "updating the outcome never rewrites the first observation");
store.ingest([{ ...closed, id: "late-H1-EURUSD-90", status: "open" }], 310, () => true);
assert.equal(store.summary().late, 1); assert.equal(store.summary().closed, 1);
store.ingest([{ ...closed, version: 2 }], 320, () => true);
assert.equal(store.summary().closed, 0, "different rules cannot be counted as the original observed result");
const groups = FX.signalTools.group([signal, { ...signal, id: "second", strategy: "second-H1" }, { ...signal, id: "swing", style: "swing" }]);
assert.equal(groups.length, 2, "day and swing are separate groups");
assert.ok(FX.signalTools.conflicts([signal, { ...signal, style: "swing", orders: [{ dir: -1 }] }], "EURUSD").opposed);
assert.equal(FX.signalTools.entryState({ ...signal, status: "open", fill_price: 1.1, stop0: 1.09 }, 1.105, 100, true).state, "passed");
context.document = { addEventListener() {} };
vm.runInContext(fs.readFileSync(path.join(root, "assets/js/risk.js"), "utf8"), context);
const risk = vm.runInContext("RiskJournal", context), timestamp = Date.now() / 1000;
const original = { id: "position", pair: "EURUSD", dir: 1, style: "day", currency: "USD", status: "open", risk: 10, risk_pct: .5, opened: timestamp - 3600, tag: "plan", note: "", lots: .1, entry_price: 1.1, initial_stop: 1.09,
  partials: [{ at: timestamp - 1000, lots: .04, price: 1.102, net: 5 }] };
const valid = risk.validate(original); near(risk.openRisk(valid), .3);
near(risk.openRisk({ ...valid, current_stop: 1.105 }), 0);
near(risk.stats([valid, { ...valid, id: "opposite", dir: -1, initial_stop: 1.11 }], timestamp).byPair.EURUSD, .6);
near(risk.estimate({ ...valid, exit_price: 1.102, pip_value: 10 }), 17);
const final = risk.validate({ ...original, status: "closed", net: -5, closed: timestamp - 10 });
near(risk.stats([final], timestamp).daily, .5, "partial wins do not replenish the gross loss budget");
assert.throws(() => risk.validate({ ...original, partials: [{ ...original.partials[0], lots: .2 }] }));
assert.throws(() => risk.validate({ ...original, lots: undefined }));
console.log("OK: swap/DST and partial volume, immutable observations, grouping, actual exposure and realized losses");
